CUSTOM = {
    "minor_digits": 2,
    "major": {
        "singular": "ليرة",
        "dual": "ليرتان",
        "plural": "ليرات",
        "gender": "feminine",
    },
    "minor": {
        "singular": "جزء",
        "dual": "جزآن",
        "plural": "أجزاء",
        "gender": "masculine",
    },
}


@pytest.mark.parametrize(
    ("value", "expected"),
    [
        ("1.01", "ليرة واحدة وجزء واحد فقط"),
        ("2.02", "ليرتان اثنتان وجزآن اثنان فقط"),
        ("3.03", "ثلاث ليرات وثلاثة أجزاء فقط"),
        ("12.12", "اثنتا عشرة ليرةً واثنا عشر جزءًا فقط"),
    ],
)
def test_custom_currency(value, expected):
    assert amount_to_arabic_words(value, CUSTOM) == expected


def test_custom_currency_without_minor_digits():
    assert amount_to_arabic_words("1.5", {**CUSTOM, "minor_digits": 0}) == "ليرتان اثنتان فقط"


def test_custom_currency_can_supply_its_own_accusative_form():
    minor = {
        "singular": "قرش مصري",
        "dual": "قرشان مصريان",
        "plural": "قروش مصرية",
        "gender": "masculine",
        "accusative": "قرشًا مصريًا",
    }
    assert amount_to_arabic_words("1.11", {**CUSTOM, "minor": minor}) == (
        "ليرة واحدة وأحد عشر قرشًا مصريًا فقط"
    )


def test_custom_currency_with_final_hamza():
    minor = {"singular": "شيء", "dual": "شيئان", "plural": "أشياء", "gender": "masculine"}
    assert amount_to_arabic_words("1.11", {**CUSTOM, "minor": minor}) == (
        "ليرة واحدة وأحد عشر شيئًا فقط"
    )


def test_rounding_ignores_callers_decimal_precision_and_traps():
    with localcontext() as context:
        context.prec = 1
        context.rounding = ROUND_DOWN
        context.traps[Inexact] = True
        assert amount_to_arabic_words(Decimal("123.455")) == (
            "مائة وثلاثة وعشرون ريالًا وست وأربعون هللةً فقط"
        )


